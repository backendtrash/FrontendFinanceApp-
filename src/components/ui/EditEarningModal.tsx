import { useState, useEffect }  from 'react'
import Modal                     from './Modal'
import Button                    from './Button'
import Input                     from './Input'
import { useUpdateEarning }      from '../../hooks/useQueries'
import { formatDate }            from '../../utils/formatters'
import type { Earning, Category, Currency } from '../../types/index'

interface EditEarningModalProps {
  earning:    Earning | null
  open:       boolean
  onClose:    () => void
  categories: Category[]
  currencies: Currency[]
}

export default function EditEarningModal({
  earning,
  open,
  onClose,
  categories,
  currencies,
}: EditEarningModalProps) {
  const updateEarning = useUpdateEarning()

  const [amount,     setAmount]     = useState('')
  const [currencyId, setCurrencyId] = useState('')
  const [categoryId, setCategoryId] = useState('')
  const [date,       setDate]       = useState('')
  const [notes,      setNotes]      = useState('')
  const [error,      setError]      = useState('')

  useEffect(() => {
    if (earning) {
      setAmount(String(Number(earning.amount)))
      setCurrencyId(earning.currency_id)
      setCategoryId(earning.category_id ?? '')
      setDate(earning.date)
      setNotes(earning.notes ?? '')
      setError('')
    }
  }, [earning])

  const handleSubmit = async () => {
    if (!earning) return
    if (!amount || parseFloat(amount) <= 0) {
      setError('Amount must be greater than zero')
      return
    }

    try {
      await updateEarning.mutateAsync({
        id: earning.id,
        data: {
          amount:      parseFloat(amount),
          currency_id: currencyId   || undefined,
          category_id: categoryId   || undefined,
          date:        date         || undefined,
          notes:       notes.trim() || undefined,
        },
      })
      onClose()
    } catch (e: any) {
      const detail = e?.response?.data?.detail
      if (Array.isArray(detail)) {
        setError(detail.map((d: any) => d.msg).join(', '))
      } else {
        setError(detail || 'Failed to update earning')
      }
    }
  }

  if (!earning) return null

  return (
    <Modal open={open} onClose={onClose} title="Edit Earning">
      <div className="space-y-4">
        <div className="p-3 bg-gray-50 rounded-lg text-xs text-gray-500">
          Created {formatDate(earning.created_at)}
          {earning.is_recurring && ' · 🔁 Generated by recurring rule'}
        </div>

        <div className="flex gap-3">
          <div className="flex-1">
            <Input
              label="Amount"
              type="number"
              step="0.01"
              min="0"
              value={amount}
              onChange={e => setAmount(e.target.value)}
            />
          </div>
          <div className="w-28">
            <label className="block text-xs font-medium text-gray-700 mb-1">
              Currency
            </label>
            <select
              className="w-full px-3 py-2 text-sm border border-gray-300
                         rounded-lg outline-none focus:ring-2 focus:ring-blue-500"
              value={currencyId}
              onChange={e => setCurrencyId(e.target.value)}
            >
              {currencies.map(c => (
                <option key={c.id} value={c.id}>{c.code}</option>
              ))}
            </select>
          </div>
        </div>

        <div>
          <label className="block text-xs font-medium text-gray-700 mb-1">
            Category
          </label>
          <select
            className="w-full px-3 py-2 text-sm border border-gray-300
                       rounded-lg outline-none focus:ring-2 focus:ring-blue-500"
            value={categoryId}
            onChange={e => setCategoryId(e.target.value)}
          >
            <option value="">No category</option>
            {categories.map(c => (
              <option key={c.id} value={c.id}>{c.name}</option>
            ))}
          </select>
        </div>

        <Input
          label="Date"
          type="date"
          value={date}
          onChange={e => setDate(e.target.value)}
        />

        <Input
          label="Notes"
          placeholder="Income source details..."
          value={notes}
          onChange={e => setNotes(e.target.value)}
        />

        {error && <p className="text-sm text-red-500">{error}</p>}

        <div className="flex gap-3 pt-2">
          <Button variant="secondary" className="flex-1" onClick={onClose}>
            Cancel
          </Button>
          <Button
            className="flex-1"
            loading={updateEarning.isPending}
            onClick={handleSubmit}
          >
            Save Changes
          </Button>
        </div>
      </div>
    </Modal>
  )
}